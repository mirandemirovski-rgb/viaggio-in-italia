// Builds assets/js/geo.js: the outline of Italy and its neighbours, projected
// onto the map's own coordinate system (a "world" of W x H units).
// Run from this folder:  npm i world-atlas@2 topojson-client@3 topojson-simplify@3 d3-geo@3
//                        node make-geo.mjs
import fs from 'node:fs';
import * as topo from 'topojson-client';
import * as simp from 'topojson-simplify';
import { geoMercator, geoPath } from 'd3-geo';

const W = 1600, H = 1250;

function load(res, weight) {
  let t = JSON.parse(fs.readFileSync(`node_modules/world-atlas/countries-${res}.json`));
  t = simp.presimplify(t);
  t = simp.simplify(t, weight);
  return topo.feature(t, t.objects.countries).features;
}

const fine = load('10m', 0.00015);
const coarse = load('10m', 0.006);
// neighbours that touch Italy must share its exact border, so they use the same detail
const touching = new Set(['France', 'Switzerland', 'Austria', 'Slovenia', 'San Marino']);
const italy = fine.find(f => f.properties.name === 'Italy');
const sanMarino = fine.find(f => f.properties.name === 'San Marino');

const proj = geoMercator().fitExtent([[380, 70], [1220, 1180]], italy);
proj.clipExtent([[-500, -500], [W + 500, H + 500]]);
const path = geoPath(proj).digits(1);

// Old-map names for the lands around Italy (shown faded, as "fog")
const latin = {
  France: 'Gallia', Switzerland: 'Helvetia', Austria: 'Noricum', Germany: 'Germania',
  Liechtenstein: '', Slovenia: 'Illyricum', Croatia: 'Dalmatia', 'Bosnia and Herz.': '',
  Montenegro: '', Albania: 'Epirus', Serbia: '', Hungary: 'Pannonia', Kosovo: '', Macedonia: '',
  'North Macedonia': '', Greece: 'Graecia', Tunisia: 'Africa', Algeria: 'Numidia', Libya: '',
  Malta: 'Melita', Monaco: '', Czechia: '', Slovakia: '', Spain: '', Bulgaria: '', Romania: '',
};

const fog = [...fine.filter(f => touching.has(f.properties.name)), ...coarse.filter(f => !touching.has(f.properties.name))]
  .filter(f => f.properties.name in latin)
  .map(f => ({ name: f.properties.name, d: path(f) || '' }))
  .filter(f => f.d.length > 0);

// drop specks smaller than a few units so the paths stay light
function clean(d) {
  return d.split('Z').filter(s => (s.match(/L/g) || []).length >= 3).map(s => s + 'Z').join('');
}

const out = {
  W, H,
  s: +proj.scale().toFixed(4),
  tx: +proj.translate()[0].toFixed(3),
  ty: +proj.translate()[1].toFixed(3),
  italy: clean(path(italy)),
  sanMarino: path(sanMarino) || '',
  fog: fog.map(f => ({ ...f, d: clean(f.d) })),
};

const js = `// Generated by tools/make-geo.mjs — do not edit by hand.
// Map data: Natural Earth (public domain) via world-atlas.
export const GEO = ${JSON.stringify(out)};
`;
fs.writeFileSync('../assets/js/geo.js', js);
console.log('italy', out.italy.length, 'fog', out.fog.reduce((a, f) => a + f.d.length, 0), 'total kB', (js.length / 1024).toFixed(1));
console.log('scale', out.s, 'translate', out.tx, out.ty);
// quick check of the projection formula used in the browser
const test = [12.5, 41.9];
const lam = test[0] * Math.PI / 180, phi = test[1] * Math.PI / 180;
const bx = out.tx + out.s * lam, by = out.ty - out.s * Math.log(Math.tan(Math.PI / 4 + phi / 2));
console.log('d3', proj(test), 'browser', [bx, by]);
